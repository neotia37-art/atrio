export const categories = ["전체", ...Array.from(new Set(guides.map((guide) => guide.category)))];

export function getGuide(slug: string) {
  return guides.find((guide) => guide.slug === slug);
}

export function relatedGuides(slug: string) {
  const current = getGuide(slug);
  if (!current) return guides.slice(0, 3);
  const same = guides.filter((guide) => guide.slug !== slug && guide.category === current.category);
  const rest = guides.filter((guide) => guide.slug !== slug && guide.category !== current.category);
  return [...same, ...rest].slice(0, 3);
}
